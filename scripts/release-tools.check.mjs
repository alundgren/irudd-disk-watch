import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
test('release manifest requires the exact assets and refuses to overwrite an existing manifest', (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'disk-watch-manifest-'))
  t.after(() => rmSync(directory, { recursive: true, force: true }))
  const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  const names = [
    'Disk-Watch-mac-arm64.tar.gz',
    `Disk-Watch-${version}-x64-Setup.exe`,
    'dw-scan-linux-x64',
    'dw-scan-linux-arm64',
  ]
  const run = () =>
    spawnSync(process.execPath, [join(root, 'scripts/release-manifest.mjs'), directory], {
      encoding: 'utf8',
      env: { ...process.env, GITHUB_REF_NAME: `v${version}` },
    })
  for (const name of names.slice(1)) writeFileSync(join(directory, name), 'fixture')
  assert.notEqual(run().status, 0)
  writeFileSync(join(directory, names[0]), 'fixture')
  assert.equal(run().status, 0)
  const before = readFileSync(join(directory, 'SHA256SUMS'), 'utf8')
  assert.equal(before.trim().split('\n').length, 4)
  assert.notEqual(run().status, 0)
  assert.equal(readFileSync(join(directory, 'SHA256SUMS'), 'utf8'), before)
})
test('PowerShell bootstrap contains the same installer functions as the bundled helper', () => {
  const helper = readFileSync(join(root, 'scripts/install-windows.ps1'), 'utf8').replaceAll('\r\n', '\n')
  const functions = helper.slice(
    helper.indexOf('function Assert-DiskWatchPath'),
    helper.lastIndexOf('\nInstall-DiskWatch -Installer'),
  )
  const expected =
    '# Generated by scripts/build-windows-bootstrap.mjs\n' +
    functions +
    '\n' +
    readFileSync(join(root, 'scripts/bootstrap-windows.ps1'), 'utf8').replaceAll('\r\n', '\n')
  assert.equal(readFileSync(join(root, 'install.ps1'), 'utf8').replaceAll('\r\n', '\n'), expected)
})

for (const token of [undefined, '', 'optional fixture token']) {
  test(
    `Mac bootstrap fetch works in system Bash with ${token === undefined ? 'unset' : token === '' ? 'empty' : 'optional'} credentials`,
    { skip: process.platform !== 'darwin' },
    () => {
      const source = readFileSync(join(root, 'install.sh'), 'utf8')
      const start = source.indexOf('fetch() {')
      const end = source.indexOf('\nfetch "', start)
      assert.ok(start >= 0 && end > start)
      const helper = source.slice(start, end)
      const script = `set -euo pipefail
function /usr/bin/curl { printf '%s\\0' "$@"; }
${helper}
fetch 'https://api.github.com/repos/fixture/app/releases/latest' '/tmp/release fixture.json' application/vnd.github+json
`
      const env = { ...process.env }
      delete env.DISK_WATCH_GITHUB_TOKEN
      if (token !== undefined) env.DISK_WATCH_GITHUB_TOKEN = token
      const result = spawnSync('/bin/bash', ['-c', script], { env, encoding: 'utf8' })
      assert.equal(result.status, 0, result.stderr)
      const args = result.stdout.split('\0').slice(0, -1)
      assert.ok(args.includes('Accept: application/vnd.github+json'))
      assert.deepEqual(args.slice(-3), [
        'https://api.github.com/repos/fixture/app/releases/latest',
        '-o',
        '/tmp/release fixture.json',
      ])
      assert.deepEqual(
        args.filter((arg) => arg.startsWith('Authorization:')),
        token ? [`Authorization: Bearer ${token}`] : [],
      )
    },
  )
}
